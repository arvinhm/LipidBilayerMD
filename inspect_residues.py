#!/usr/bin/env python
"""
Loads a PSF file and lists all unique residue names found.
"""

import sys
import parmed as pmd

# --- Configuration ---
psf_file = "merged.psf" # The PSF file generated by the simulation script
# -------------------

if __name__ == "__main__":
    print(f"Inspecting residue names in: {psf_file}")

    # Check for ParmEd
    try:
        import parmed
    except ImportError:
        print("Error: ParmEd library is required but not found.")
        print("Please install it, e.g., using 'pip install parmed'")
        sys.exit(1)

    # Load the PSF file
    try:
        structure = pmd.load_file(psf_file)
        print(f"Successfully loaded {psf_file}.")
    except FileNotFoundError:
        print(f"Error: PSF file '{psf_file}' not found.")
        print("Make sure you have run 'run_merged_simulation.py' successfully first.")
        sys.exit(1)
    except Exception as e:
        print(f"Error loading PSF file '{psf_file}': {e}")
        sys.exit(1)

    # Collect unique residue names
    unique_residue_names = set()
    for residue in structure.residues:
        unique_residue_names.add(residue.name)

    if not unique_residue_names:
        print("No residues found in the structure.")
    else:
        print("\nUnique residue names found:")
        # Sort for consistent output
        sorted_names = sorted(list(unique_residue_names))
        for name in sorted_names:
            print(f"- {name}")

    print("Inspection complete.") 